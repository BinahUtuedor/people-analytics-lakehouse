    def test_g02_hire_date_event_precedence(self):
        # A later role change ensures current role differs from hire-day role.
        first = self.promotions.withColumn("promotion_date", F.lit(date(2023, 12, 31)))
        later = (
            self.promotions.withColumn("promotion_id", F.lit(11).cast("long"))
            .withColumn("old_role_id", F.lit(2).cast("long"))
            .withColumn("new_role_id", F.lit(1).cast("long"))
        )
        self.promotions = first.unionByName(later)
        self.employees = self.employees.withColumn("role_id", F.lit(1).cast("long"))
        row = (
            self.assignments()
            .filter("employee_key = 1")
            .orderBy("valid_from_date")
            .first()
        )
        self.assertEqual(row.job_role_key, 2)
        self.assertEqual(row.role_history_basis, "event-derived")

