    def test_g03_exit_date_assignment_boundary(self):
        self.transfers = self.transfers.withColumn(
            "employee_id", F.lit(2).cast("long")
        ).withColumn("transfer_date", F.lit(date(2024, 2, 29)))
        assignments, movements = history.Phase2SmokeTests.build_pair(self)
        final = (
            assignments.filter("employee_key = 2")
            .orderBy(F.col("valid_from_date").desc())
            .first()
        )
        event = movements.filter("movement_type = 'EXIT'").first()
        self.assertEqual(event.before_assignment_key, final.assignment_key)
        self.assertEqual(event.before_department_key, 2)
        self.assertEqual(event.after_assignment_key, "0")
        self.assertEqual(event.headcount_delta, -1)

