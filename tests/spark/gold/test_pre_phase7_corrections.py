    def test_g02_contradictory_chain_evidence(self):
        for attribute, source_name, date_name, id_name, old_name in (
            ("role", "promotions", "promotion_date", "promotion_id", "old_role_id"),
            (
                "department",
                "transfers",
                "transfer_date",
                "transfer_id",
                "old_department_id",
            ),
            (
                "location",
                "transfers",
                "transfer_date",
                "transfer_id",
                "old_location_id",
            ),
            ("manager", "transfers", "transfer_date", "transfer_id", "old_manager_id"),
        ):
            with self.subTest(attribute=attribute):
                original = getattr(self, source_name)
                later = original.withColumn(
                    date_name, F.lit(date(2024, 2, 15))
                ).withColumn(id_name, F.lit(99).cast("long"))
                # Reconcile other attributes so the named contradiction is isolated.
                for field in original.columns:
                    if field.startswith("old_"):
                        later = later.withColumn(
                            field, F.col(field.replace("old_", "new_"))
                        )
                later = later.withColumn(old_name, F.lit(99).cast("long"))
                setattr(self, source_name, original.unionByName(later))
                with self.assertRaisesRegex(
                    GoldValidationError, "history_continuity_" + attribute
                ):
                    self.assignments()
                setattr(self, source_name, original)

