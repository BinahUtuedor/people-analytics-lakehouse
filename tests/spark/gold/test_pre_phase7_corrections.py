        with self.assertRaisesRegex(GoldValidationError, "attendance_source_schema"):
            normalize_attendance_source(
                self.attendance_source("Absent", "Medical Appointment").withColumn(
                    "absence_reason", F.lit(123)
                ),
                self.build,
            )

