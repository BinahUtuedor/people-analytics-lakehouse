    def test_g04_domain_change_changes_build_identity_and_stale_build_fails(self):
        changed = replace(self.build.spec, absence_domain_digest="b" * 64)
        self.assertNotEqual(self.build.spec.build_id, changed.build_id)
        with self.assertRaisesRegex(ValueError, "Governed absence domain"):
            changed.require_supported()
        with patch(
            "spark.gold.reference.absence_domain",
            return_value=(*absence_domain(), "New governed category"),
        ):
            self.assertNotEqual(
                self.build.spec.build_id,
                replace(
                    self.build.spec,
                    absence_domain_digest=absence_domain_fingerprint(),
                ).build_id,
            )
            with self.assertRaisesRegex(ValueError, "Governed absence domain"):
                normalize_attendance_source(
                    self.attendance_source("Absent", "Medical Appointment"), self.build
                )
